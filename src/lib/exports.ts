/**
 * Export helpers: CSS custom properties, JSON, plain-text reports and CSV.
 *
 * All exporters are pure functions returning strings, so they can be unit-tested without a DOM.
 * Nothing is uploaded anywhere; the UI copies the string or triggers a local download.
 */
import type { RGBA } from './color';
import { formatHsl, formatRgb, rgbToHex, rgbToHsl, normalizeColor } from './color';
import { contrastRatio, formatRatio, roundRatio, TEXT_THRESHOLDS, NON_TEXT_THRESHOLD } from './wcag';
import type { ThresholdResult } from './wcag';
import { createTranslator } from '../i18n/format';
import type { Translator } from '../i18n/format';
import type { Message } from '../i18n/messages';
import type { Locale } from '../i18n/translations';

export interface ExportColor {
  readonly id: string;
  readonly name: string;
  readonly color: RGBA;
  /** Optional role hint, e.g. "text" or "surface". */
  readonly role?: string;
}

export type CssVariableCase = 'preserve' | 'kebab' | 'camel';

export interface CssExportOptions {
  /** Optional selector, defaults to `:root`. */
  readonly selector?: string;
  /** Prefix for every custom property, defaults to `--cj-`. */
  readonly prefix?: string;
  /** Whether to append a contrast comment against `referenceBackground`. */
  readonly includeContrastComments?: boolean;
  /** Background used for the contrast comments. */
  readonly referenceBackground?: RGBA;
  /** Format used for the values. */
  readonly format?: 'hex' | 'rgb' | 'hsl';
  readonly includeHeader?: boolean;
  readonly case?: CssVariableCase;
}

const LATIN_FOLD: ReadonlyArray<readonly [RegExp, string]> = [
  [/ß/g, 'ss'],
  [/æ/g, 'ae'],
  [/œ/g, 'oe'],
  [/ø/g, 'o'],
  [/đ|ð/g, 'd'],
  [/ł/g, 'l'],
  [/þ/g, 'th'],
  [/ħ/g, 'h'],
  [/ı/g, 'i'],
  [/ŋ/g, 'n'],
];

/** Folds Latin letters that NFKD leaves alone (ß, æ, ø …) into ASCII equivalents. */
function foldLatin(value: string): string {
  let out = value.normalize('NFKD').replace(/[\u0300-\u036f]/g, '');
  for (const [pattern, replacement] of LATIN_FOLD) out = out.replace(pattern, replacement);
  return out;
}

/** Turns a display name into a CSS-safe custom property fragment. */
export function toCssPropertyName(name: string, mode: CssVariableCase = 'kebab'): string {
  const ascii = foldLatin(name)
    // Keep Latin letters/digits, collapse everything else into dashes.
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  const fallback = ascii === '' ? 'color' : ascii;

  if (mode === 'preserve') return fallback;
  if (mode === 'camel') {
    const parts = fallback.split('-').filter(Boolean);
    return parts
      .map((part, index) =>
        index === 0 ? part.toLowerCase() : part.charAt(0).toUpperCase() + part.slice(1).toLowerCase(),
      )
      .join('');
  }
  return fallback
    .split('-')
    .filter(Boolean)
    .map((part) => part.toLowerCase())
    .join('-');
}

function cssValue(color: RGBA, format: CssExportOptions['format']): string {
  switch (format) {
    case 'rgb':
      return formatRgb(color);
    case 'hsl':
      return formatHsl(color);
    default:
      return rgbToHex(color, { alpha: normalizeColor(color).a < 1 }).toUpperCase();
  }
}

/** Builds a `:root { --cj-name: #RRGGBB; }` block. */
export function toCssVariables(colors: readonly ExportColor[], options: CssExportOptions = {}): string {
  const selector = options.selector ?? ':root';
  const prefix = options.prefix ?? '--cj-';
  const format = options.format ?? 'hex';
  const includeComments = options.includeContrastComments ?? true;
  const reference = options.referenceBackground;
  const includeHeader = options.includeHeader ?? true;
  const nameCase = options.case ?? 'kebab';

  const usedNames = new Map<string, number>();
  const lines: string[] = [];

  for (const entry of colors) {
    const base = toCssPropertyName(entry.name || entry.id, nameCase);
    const count = usedNames.get(base) ?? 0;
    usedNames.set(base, count + 1);
    const unique = count === 0 ? base : `${base}-${count + 1}`;
    const value = cssValue(entry.color, format);
    const comment =
      includeComments && reference
        ? ` /* ${formatRatio(contrastRatio(entry.color, reference))} on ${rgbToHex(reference).toUpperCase()} */`
        : '';
    lines.push(`  ${prefix}${unique}: ${value};${comment}`);
  }

  const header = includeHeader
    ? [
        '/* Generated by ContrastJudge — https://github.com/iiiiiiiiiiiiiKK/contrastjudge */',
        '/* Ratios are measured against the reference background noted in each comment. */',
      ].join('\n')
    : '';

  const body = `${selector} {\n${lines.join('\n')}\n}`;
  return header ? `${header}\n${body}\n` : `${body}\n`;
}

export interface JsonExportOptions {
  readonly name?: string;
  readonly includeHsl?: boolean;
  readonly includeRgb?: boolean;
  readonly includeContrastMatrix?: boolean;
  /** Pairs to include in the contrast matrix; if omitted, every colour is compared with every colour. */
  readonly pairs?: readonly { foreground: string; background: string }[];
}

/** Structured JSON export, suitable for design-token pipelines. */
export function toJson(colors: readonly ExportColor[], options: JsonExportOptions = {}): string {
  const includeHsl = options.includeHsl ?? true;
  const includeRgb = options.includeRgb ?? true;

  const payload = {
    $schema: 'https://contrastjudge.local/schema/palette-1.0.json',
    generator: 'ContrastJudge',
    generatorVersion: 1,
    name: options.name ?? 'ContrastJudge palette',
    exportedAt: new Date().toISOString(),
    standard: {
      spec: 'WCAG 2.2',
      luminanceFormula: 'L = 0.2126R + 0.7152G + 0.0722B (linearised sRGB)',
      contrastFormula: '(L1 + 0.05) / (L2 + 0.05)',
      thresholds: [...TEXT_THRESHOLDS, NON_TEXT_THRESHOLD].map((definition) => ({
        criterion: definition.criterion,
        name: definition.criterionName,
        level: definition.level,
        threshold: definition.threshold,
        appliesTo: definition.appliesTo,
      })),
    },
    colors: colors.map((entry) => {
      const color = normalizeColor(entry.color);
      return {
        id: entry.id,
        name: entry.name,
        role: entry.role ?? null,
        hex: rgbToHex(color, { alpha: color.a < 1 }).toUpperCase(),
        ...(includeRgb ? { rgb: { r: color.r, g: color.g, b: color.b }, alpha: Number(color.a.toFixed(3)) } : {}),
        ...(includeHsl ? { hsl: roundHsl(rgbToHsl(color)) } : {}),
      };
    }),
    ...(options.includeContrastMatrix === false
      ? {}
      : {
          contrast: buildContrastMatrix(colors, options.pairs),
        }),
  };

  return `${JSON.stringify(payload, null, 2)}\n`;
}

function roundHsl(hsl: { h: number; s: number; l: number; a: number }) {
  return {
    h: roundRatio(hsl.h, 1),
    s: roundRatio(hsl.s, 1),
    l: roundRatio(hsl.l, 1),
    a: Number(hsl.a.toFixed(3)),
  };
}

function buildContrastMatrix(
  colors: readonly ExportColor[],
  pairs?: readonly { foreground: string; background: string }[],
): {
  ratioFormula: string;
  pairs: {
    foreground: string;
    background: string;
    ratio: number;
    aaNormal: boolean;
    aaLarge: boolean;
    aaaNormal: boolean;
    aaaLarge: boolean;
    nonTextAa: boolean;
  }[];
} {
  const byId = new Map(colors.map((entry) => [entry.id, entry]));
  const resolvedPairs: { foreground: string; background: string }[] = pairs
    ? [...pairs]
    : colors.flatMap((fg) => colors.map((bg) => ({ foreground: fg.id, background: bg.id })));

  const rows = resolvedPairs
    .map(({ foreground, background }) => {
      const fg = byId.get(foreground);
      const bg = byId.get(background);
      if (!fg || !bg) return null;
      const ratio = contrastRatio(fg.color, bg.color);
      return {
        foreground,
        background,
        ratio: roundRatio(ratio, 2),
        aaNormal: ratio >= 4.5,
        aaLarge: ratio >= 3,
        aaaNormal: ratio >= 7,
        aaaLarge: ratio >= 4.5,
        nonTextAa: ratio >= 3,
      };
    })
    .filter((row): row is NonNullable<typeof row> => row !== null);

  return { ratioFormula: '(L1 + 0.05) / (L2 + 0.05)', pairs: rows };
}

export interface BatchRow {
  readonly label: string;
  readonly foreground: RGBA;
  readonly background: RGBA;
  readonly fontSizePx: number;
  readonly bold: boolean;
}

export interface BatchRowResult {
  readonly label: string;
  readonly foregroundHex: string;
  readonly backgroundHex: string;
  readonly ratio: number;
  readonly results: readonly ThresholdResult[];
  readonly passesAaNormal: boolean;
  readonly passesAaaNormal: boolean;
  readonly passesNonText: boolean;
  /** Summary of the first failing threshold, as a dictionary key plus params. */
  readonly worstFailure: Message | null;
}

/**
 * Human-readable Markdown report for the batch checker.
 *
 * `t` supplies the surrounding prose so a Chinese user gets a Chinese report; the table structure
 * and the ratios are language-independent.
 */
export function toMarkdownReport(
  rows: readonly BatchRowResult[],
  options: {
    title?: string;
    generatedAt?: Date;
    note?: string;
    t?: Translator;
    locale?: Locale;
  } = {},
): string {
  const generatedAt = options.generatedAt ?? new Date();
  const locale: Locale = options.locale ?? 'en';
  const t: Translator = options.t ?? createTranslator(locale);
  const title = options.title ?? t('report.defaultTitle');
  const lines: string[] = [];
  lines.push(`# ${title}`);
  lines.push('');
  lines.push(t('report.generatedOn', { date: generatedAt.toISOString().slice(0, 10) }));
  lines.push('');
  lines.push(t('report.thresholdsNote'));
  lines.push('');
  lines.push(
    `| ${t('report.colPair')} | ${t('report.colForeground')} | ${t('report.colBackground')} | ${t('report.colRatio')} | ${t('report.colAaText')} | ${t('report.colAaLarge')} | ${t('report.colAaaText')} | ${t('report.colAaaLarge')} | ${t('report.colNonText')} |`,
  );
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  const mark = (value: boolean) => (value ? '✅' : '❌');
  for (const row of rows) {
    const get = (id: string) => row.results.find((result) => result.id === id)?.passes ?? false;
    lines.push(
      `| ${escapePipes(row.label)} | \`${row.foregroundHex}\` | \`${row.backgroundHex}\` | ${formatRatio(row.ratio)} | ${mark(get('aa-normal'))} | ${mark(get('aa-large'))} | ${mark(get('aaa-normal'))} | ${mark(get('aaa-large'))} | ${mark(get('aa-non-text'))} |`,
    );
  }
  lines.push('');
  const failing = rows.filter((row) => !row.passesAaNormal);
  lines.push(t('report.summary', { total: rows.length, failing: failing.length }));
  if (options.note) {
    lines.push('');
    lines.push(options.note);
  }
  lines.push('');
  lines.push(t('report.disclaimer'));
  return lines.join('\n');
}

/** CSV report, RFC 4180 quoting. */
export function toCsvReport(rows: readonly BatchRowResult[]): string {
  const header = [
    'label',
    'foreground',
    'background',
    'ratio',
    'aa_normal',
    'aa_large',
    'aaa_normal',
    'aaa_large',
    'non_text_aa',
  ];
  const escape = (value: string) => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value);
  const lines = [header.join(',')];
  for (const row of rows) {
    const get = (id: string) => (row.results.find((result) => result.id === id)?.passes ? 'pass' : 'fail');
    lines.push(
      [
        escape(row.label),
        row.foregroundHex,
        row.backgroundHex,
        roundRatio(row.ratio, 2).toFixed(2),
        get('aa-normal'),
        get('aa-large'),
        get('aaa-normal'),
        get('aaa-large'),
        get('aa-non-text'),
      ].join(','),
    );
  }
  return `${lines.join('\n')}\n`;
}

function escapePipes(value: string): string {
  return value.replace(/\|/g, '\\|');
}

/** Copy-to-clipboard with a graceful fallback for insecure contexts. */
export async function copyText(text: string): Promise<{ ok: true } | { ok: false; message: string }> {
  try {
    if (typeof navigator !== 'undefined' && navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return { ok: true };
    }
    if (typeof document !== 'undefined') {
      const textarea = document.createElement('textarea');
      textarea.value = text;
      textarea.setAttribute('readonly', '');
      textarea.style.position = 'fixed';
      textarea.style.opacity = '0';
      document.body.appendChild(textarea);
      textarea.select();
      const succeeded = document.execCommand('copy');
      document.body.removeChild(textarea);
      if (succeeded) return { ok: true };
    }
    return { ok: false, message: 'Copying is blocked by the browser. Select the text and copy manually.' };
  } catch (error) {
    return { ok: false, message: error instanceof Error ? error.message : 'Copy failed.' };
  }
}

/** Triggers a local file download without touching the network. */
export function downloadFile(filename: string, content: string, mime = 'text/plain;charset=utf-8'): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  // Give the browser a tick to start the download before revoking.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** A stable filename stem from a user-supplied name. */
export function slugify(value: string, fallback = 'contrastjudge'): string {
  const slug = foldLatin(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
  return slug === '' ? fallback : slug;
}
