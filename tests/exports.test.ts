import { describe, expect, it } from 'vitest';
import { parseColorOrThrow } from '../src/lib/color';
import {
  slugify,
  toCssPropertyName,
  toCssVariables,
  toCsvReport,
  toJson,
  toMarkdownReport,
} from '../src/lib/exports';
import type { ExportColor } from '../src/lib/exports';
import { evaluateBatch } from '../src/lib/batch';

const COLORS: ExportColor[] = [
  { id: 'a', name: 'Ink', color: parseColorOrThrow('#0f172a'), role: 'text' },
  { id: 'b', name: 'Paper', color: parseColorOrThrow('#ffffff'), role: 'surface' },
  { id: 'c', name: 'Accent Blue', color: parseColorOrThrow('#1f4fd8'), role: 'accent' },
];

describe('toCssPropertyName', () => {
  it('kebab-cases names and strips unsupported characters', () => {
    expect(toCssPropertyName('Accent Blue')).toBe('accent-blue');
    expect(toCssPropertyName('  brand / primary  ')).toBe('brand-primary');
    expect(toCssPropertyName('Caf\u00e9 Cr\u00e8me')).toBe('cafe-creme');
    expect(toCssPropertyName('!!!')).toBe('color');
    expect(toCssPropertyName('Accent Blue', 'camel')).toBe('accentBlue');
    expect(toCssPropertyName('Accent Blue', 'preserve')).toBe('Accent-Blue');
  });
});

describe('toCssVariables', () => {
  it('emits a :root block with the requested prefix and format', () => {
    const css = toCssVariables(COLORS, { format: 'hex' });
    expect(css).toContain(':root {');
    expect(css).toContain('--cj-ink: #0F172A;');
    expect(css).toContain('--cj-paper: #FFFFFF;');
    expect(css).toContain('--cj-accent-blue: #1F4FD8;');
    expect(css.trim().endsWith('}')).toBe(true);
  });

  it('writes rgb()/hsl() values when requested', () => {
    expect(toCssVariables(COLORS, { format: 'rgb' })).toContain('--cj-ink: rgb(15, 23, 42);');
    expect(toCssVariables(COLORS, { format: 'hsl' })).toContain('--cj-ink: hsl(222.2, 47.4%, 11.2%);');
  });

  it('includes accurate contrast comments against the reference background', () => {
    const css = toCssVariables(COLORS, { referenceBackground: parseColorOrThrow('#ffffff') });
    // #0f172a on white is 17.85:1
    expect(css).toMatch(/--cj-ink: #0F172A; \/\* 17\.85:1 on #FFFFFF \*\//);
    // #ffffff on white is 1:1
    expect(css).toMatch(/--cj-paper: #FFFFFF; \/\* 1\.00:1 on #FFFFFF \*\//);
  });

  it('de-duplicates repeated names with numeric suffixes', () => {
    const css = toCssVariables(
      [
        { id: '1', name: 'Grey', color: parseColorOrThrow('#111111') },
        { id: '2', name: 'Grey', color: parseColorOrThrow('#222222') },
      ],
      { includeContrastComments: false, includeHeader: false },
    );
    expect(css).toContain('--cj-grey: #111111;');
    expect(css).toContain('--cj-grey-2: #222222;');
  });

  it('honours a custom selector and omits the header on request', () => {
    const css = toCssVariables(COLORS, { selector: ':root, [data-theme="dark"]', includeHeader: false });
    expect(css.startsWith(':root, [data-theme="dark"] {')).toBe(true);
    expect(css).not.toContain('Generated by ContrastJudge');
  });

  it('preserves alpha in hex output', () => {
    const css = toCssVariables([{ id: 'x', name: 'Scrim', color: { r: 0, g: 0, b: 0, a: 0.5 } }], {
      includeContrastComments: false,
    });
    expect(css).toContain('--cj-scrim: #00000080;');
  });
});

describe('toJson', () => {
  const json = JSON.parse(toJson(COLORS, { name: 'Test palette' }));

  it('is valid JSON with the expected structure', () => {
    expect(json.name).toBe('Test palette');
    expect(json.generator).toBe('ContrastJudge');
    expect(json.colors).toHaveLength(3);
    expect(json.colors[0]).toMatchObject({ id: 'a', name: 'Ink', hex: '#0F172A', role: 'text' });
    expect(json.standard.spec).toBe('WCAG 2.2');
  });

  it('includes the full contrast matrix with correct verdicts', () => {
    expect(json.contrast.pairs).toHaveLength(9);
    const inkOnPaper = json.contrast.pairs.find(
      (pair: { foreground: string; background: string }) => pair.foreground === 'a' && pair.background === 'b',
    );
    expect(inkOnPaper.ratio).toBe(17.85);
    expect(inkOnPaper.aaNormal).toBe(true);
    expect(inkOnPaper.aaaNormal).toBe(true);

    const paperOnPaper = json.contrast.pairs.find(
      (pair: { foreground: string; background: string }) => pair.foreground === 'b' && pair.background === 'b',
    );
    expect(paperOnPaper.ratio).toBe(1);
    expect(paperOnPaper.aaNormal).toBe(false);
  });

  it('can restrict the matrix to explicit pairs', () => {
    const limited = JSON.parse(toJson(COLORS, { pairs: [{ foreground: 'a', background: 'b' }] }));
    expect(limited.contrast.pairs).toHaveLength(1);
  });

  it('rounds numbers rather than dumping floating point noise', () => {
    const parsed = JSON.parse(toJson(COLORS, { includeContrastMatrix: false }));
    for (const color of parsed.colors) {
      expect(String(color.hsl.h).length).toBeLessThan(8);
      expect(String(color.hsl.s).length).toBeLessThan(8);
    }
    expect(parsed.contrast).toBeUndefined();
  });
});

describe('reports', () => {
  const rows = evaluateBatch([
    {
      label: 'Body on white',
      foreground: parseColorOrThrow('#0f172a'),
      background: parseColorOrThrow('#ffffff'),
      fontSizePx: 16,
      bold: false,
    },
    {
      label: 'Muted caption',
      foreground: parseColorOrThrow('#9aa4b2'),
      background: parseColorOrThrow('#ffffff'),
      fontSizePx: 16,
      bold: false,
    },
  ]);

  it('writes a markdown table with a verdict per criterion', () => {
    const markdown = toMarkdownReport(rows, { title: 'Audit' });
    expect(markdown).toContain('# Audit');
    expect(markdown).toContain('| Pair | Foreground | Background | Ratio | AA text |');
    expect(markdown).toContain('Body on white');
    expect(markdown).toContain('✅');
    expect(markdown).toContain('❌');
    expect(markdown).toContain('1 fail AA for normal-size text');
    expect(markdown).toContain('does not mean the page conforms to WCAG as a whole');
  });

  it('escapes pipes in labels so the table stays valid', () => {
    const markdown = toMarkdownReport([
      {
        ...rows[0]!,
        label: 'Header | footer',
      },
    ]);
    expect(markdown).toContain('Header \\| footer');
  });

  it('writes CSV with a header row and one row per pair', () => {
    const csv = toCsvReport(rows);
    const lines = csv.trim().split('\n');
    expect(lines[0]).toBe('label,foreground,background,ratio,aa_normal,aa_large,aaa_normal,aaa_large,non_text_aa');
    expect(lines).toHaveLength(3);
    expect(lines[1]).toContain('Body on white,#0F172A,#FFFFFF,17.85,pass,pass,pass,pass,pass');
    expect(lines[2]).toContain('Muted caption,#9AA4B2,#FFFFFF,2.52,fail,fail,fail,fail,fail');
  });

  it('quotes CSV fields that need it', () => {
    const csv = toCsvReport([{ ...rows[0]!, label: 'Has, comma' }]);
    expect(csv).toContain('"Has, comma"');
  });
});

describe('slugify', () => {
  it('produces safe filenames', () => {
    expect(slugify('Design System Audit')).toBe('design-system-audit');
    expect(slugify('  \u00dcber  Stra\u00dfe!! ')).toBe('uber-strasse');
    expect(slugify('')).toBe('contrastjudge');
    expect(slugify('!!!')).toBe('contrastjudge');
  });
});
