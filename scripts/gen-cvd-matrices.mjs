// Generates src/lib/cvd-matrices.ts from tmp-machado.json (Machado, Oliveira & Fernandes 2009,
// "A Physiologically-based Model for Simulation of Color Vision Deficiency").
// Table 1 of https://www.inf.ufrgs.br/~oliveira/pubs_files/CVD_Simulation/CVD_Simulation.html
import fs from 'node:fs';

const table = JSON.parse(fs.readFileSync(new URL('../tmp-machado.json', import.meta.url), 'utf8'));

/** Rows sorted by severity, each [severity, protan(9), deutan(9), tritan(9)]. */
const rows = Object.keys(table)
  .map(Number)
  .sort((a, b) => a - b)
  .map((sev) => {
    const key = sev.toFixed(1);
    const row = table[key];
    return { severity: sev, protan: row.protan, deutan: row.deutan, tritan: row.tritan };
  });

const body = rows
  .map(
    (r) =>
      `  { severity: ${r.severity}, protan: [${r.protan.join(', ')}], deutan: [${r.deutan.join(', ')}], tritan: [${r.tritan.join(', ')}] },`,
  )
  .join('\n');

const out = `// Generated by scripts/gen-cvd-matrices.mjs — do not edit by hand.
// Machado, Oliveira & Fernandes (2009), severity step 0.1, matrices for linear-light RGB.
export interface CvdMatrixRow {
  severity: number;
  /** Protanomaly / protanopia simulation matrix, row-major 3x3. */
  protan: readonly number[];
  /** Deuteranomaly / deuteranopia simulation matrix, row-major 3x3. */
  deutan: readonly number[];
  /** Tritanomaly / tritanopia simulation matrix, row-major 3x3. */
  tritan: readonly number[];
}

export const CVD_MATRIX_TABLE: readonly CvdMatrixRow[] = [
${body}
];
`;
fs.writeFileSync(new URL('../src/lib/cvd-matrices.ts', import.meta.url), out);
console.log('severity rows:', rows.length);
