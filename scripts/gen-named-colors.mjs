// Generates src/lib/named-colors.ts from named-colors.json (CSS Color Module Level 4 named colours).
import fs from 'node:fs';

const src = JSON.parse(fs.readFileSync(new URL('../named-colors.json', import.meta.url), 'utf8'));
const entries = Object.keys(src)
  .sort()
  .map((name) => `  ${name}: '${src[name]}',`);

const extra = ["  transparent: '#00000000',"];
const out = `// Generated by scripts/gen-named-colors.mjs — do not edit by hand.
// Source: CSS Color Module Level 4 named colours (148 keywords) + "transparent".
export const NAMED_COLORS: Readonly<Record<string, string>> = {
${entries.join('\n')}
${extra.join('\n')}
};

export const NAMED_COLOR_NAMES: readonly string[] = Object.keys(NAMED_COLORS);
`;
fs.writeFileSync(new URL('../src/lib/named-colors.ts', import.meta.url), out);
console.log('named colours:', entries.length);
